export const moduleFor = (path: string) =>
  [...modules]
    .sort((a, b) => b.path.length - a.path.length)
    .find((m) => path === m.path || path.startsWith(m.path + '/'));
export const resourceModule = (resource: string) => modules.find((m) => m.resource === resource);
